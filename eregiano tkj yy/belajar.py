def add(x, y):
    return x + y

def subtract(x, y):
    return x - y

def multiply(x, y):
    return x * y

def devide(x, y):
    return x / y

print("Penjumlahan:", add(5, 400000000000000000))
print("Pengurangan:", subtract(500, 5))
print("Perkalian:", multiply(45, 599))
print("Pembagian:", devide (45, 5))




def min_of_three(a,b,c):
    return min(a,b,c)
print("Angka terkecil dari 5, 500, dan 5000:",min_of_three(5,500,5000))
